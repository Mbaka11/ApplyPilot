function chooseLanguage(saved, browserLanguage = 'en') {
  if (saved === 'fr' || saved === 'en') return saved;
  return /^fr(?:-|$)/i.test(browserLanguage) ? 'fr' : 'en';
}

function translate(source, language = 'fr', values = {}) {
  const s = String(source ?? '');
  const template = language === 'en' ? EN[s] ?? translateDynamic(s) : s;
  return template.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

// Only known system-message patterns are translated. Captured data (names, paths, answers) stay intact.
function translateDynamic(s) {
  const patterns = [
    [/^pi répond à (\d+) questions?…$/, (_, n) => `pi is answering ${n} question${n === '1' ? '' : 's'}…`],
    [/^À compléter dans profile\.yaml → (.+)$/, (_, path) => `Complete profile.yaml → ${path}`],
    [/^Non sélectionnés : (.+)$/, (_, list) => `Not selected: ${list}`],
    [/^Non trouvés : (.+)$/, (_, list) => `Not found: ${list}`],
    [/^Tronqué à (\d+) caractères$/, (_, n) => `Truncated to ${n} characters`],
    [/^Tu as travaillé chez (.+)$/, (_, name) => `You worked at ${name}`],
    [/^Pas de (\d+)e (expérience|formation|langue|site Web) dans le profil$/, (_, n, kind) => `No ${({ expérience: 'experience entry', formation: 'education entry', langue: 'language entry', 'site Web': 'website' })[kind]} #${n} in your profile`],
    [/^Niveau du profil : (.+)$/, (_, level) => `Profile level: ${level}`],
    [/^GPA minimum (.+)$/, (_, min) => `Minimum GPA: ${min}`],
    [/^Ton GPA actuel : (.+)$/, (_, gpa) => `Your current GPA: ${gpa}`],
    [/^Date limite : (.+)$/, (_, date) => `Deadline: ${date}`],
    [/^Niveau — (.+)$/, (_, name) => `Level — ${name}`],
    [/^langue ([A-Z]+)$/, (_, lang) => `${lang} language`],
    [/^mots-clés : (.+)$/, (_, tags) => `keywords: ${tags}`],
    [/^(\d+) cases? cochées?$/, (_, n) => `${n} checked box(es)`],
    [/^CV(?: \+ lettre)? \((.+)\)$/, (_, names) => `CV${s.startsWith('CV +') ? ' + letter' : ''} (${names})`],
    [/^pi n’a pas répondu après (\d+) s$/, (_, seconds) => `pi did not respond within ${seconds} seconds`],
    [/^Impossible de lancer pi \((.+?)\) : (.+)$/s, (_, runner, reason) => `Cannot start pi (${runner}): ${reason}`],
    [/^pi a échoué \(code (.+?)\) : (.+)$/s, (_, code, reason) => `pi failed (code ${code}): ${reason}`],
    [/^Réponse de pi illisible \(JSON attendu\) : (.+)$/s, (_, answer) => `Cannot parse pi’s response (expected JSON): ${answer}`],
    [/^Erreur (\d+)$/, (_, code) => `Error ${code}`],
    [/^Langues? (\d+)$/, (_, n) => `Language ${n}`],
    [/^Type non géré : (.+)$/, (_, type) => `Unsupported field type: ${type}`],
    [/^Champ non modifiable : (.+)$/, (_, path) => `Field is not editable: ${path}`],
    [/^(CV|Dossier de CV|Candidature) introuvable : (.+)$/, (_, kind, value) => `${({ CV: 'CV', 'Dossier de CV': 'CV folder', Candidature: 'Application' })[kind]} not found: ${value}`],
    [/^Profil YAML invalide : (.+)$/s, (_, reason) => `Invalid profile YAML: ${reason}`],
    [/^Erreur de syntaxe YAML dans (.+?) : (.+)$/s, (_, file, reason) => `YAML syntax error in ${file}: ${reason}`],
    [/^Statut inconnu : (.+)$/, (_, status) => `Unknown status: ${status}`],
    [/^Route inconnue : (.+)$/, (_, route) => `Unknown route: ${route}`],
    [/^Origine refusée \((.+)\)$/, (_, origin) => `Origin rejected (${origin})`],
    [/^fichier introuvable \((.+)\)\.$/, (_, file) => `file not found (${file}).`],
    [/^entier entre (\d+) et (\d+) attendu\.$/, (_, min, max) => `a whole number between ${min} and ${max} is required.`],
    [/^Impossible d’écrire (.+?) \((.+?)\)\. Ferme le PDF s’il est ouvert dans un lecteur\.$/, (_, file, code) => `Cannot write ${file} (${code}). Close it if it is open in a PDF reader.`],
  ];
  for (const [pattern, replacement] of patterns) if (pattern.test(s)) return s.replace(pattern, replacement);
  if (s.includes(' · ')) return s.split(' · ').map((part) => translate(part, 'en')).join(' · ');
  const colon = s.indexOf(' : ');
  if (colon > 0) {
    const left = translate(s.slice(0, colon), 'en');
    const right = translate(s.slice(colon + 3), 'en');
    if (left !== s.slice(0, colon) || right !== s.slice(colon + 3)) return `${left}: ${right}`;
  }
  return s;
}

